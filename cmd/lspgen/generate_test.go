func TestExportedName(t *testing.T) {
	tests := []struct {
		prop string
		want string
	}{
		{"uri", "URI"},
		{"languageId", "LanguageID"},
		{"textDocument", "TextDocument"},
		{"startCharacter", "StartCharacter"},
		{"hierarchicalDocumentSymbolSupport", "HierarchicalDocumentSymbolSupport"},
		{"includeDeclaration", "IncludeDeclaration"},
		{"containerName", "ContainerName"},
		{"newText", "NewText"},
		{"relatedInformation", "RelatedInformation"},
		{"query", "Query"},
		{"kind", "Kind"},
		{"targetUri", "TargetURI"},
	}
	for _, tt := range tests {
		t.Run(tt.prop, func(t *testing.T) {
			if got := exportedName(tt.prop); got != tt.want {
				t.Errorf("exportedName(%q) = %q, want %q", tt.prop, got, tt.want)
			}
		})
	}
}

func TestSplitCamelWords(t *testing.T) {
	tests := []struct {
		in   string
		want []string
	}{
		{"uri", []string{"uri"}},
		{"languageId", []string{"language", "Id"}},
		{"hierarchicalDocumentSymbolSupport", []string{"hierarchical", "Document", "Symbol", "Support"}},
	}
	for _, tt := range tests {
		got := splitCamelWords(tt.in)
		if len(got) != len(tt.want) {
			t.Fatalf("splitCamelWords(%q) = %v, want %v", tt.in, got, tt.want)
		}
		for i := range got {
			if got[i] != tt.want[i] {
				t.Errorf("splitCamelWords(%q)[%d] = %q, want %q", tt.in, i, got[i], tt.want[i])
			}
		}
	}
}

// TestEmbeddedMetaModelSHA256 pins the vendored metaModel.json; if this ever
// fails it means the file was edited without updating the pin (in main.go)
// — see the same check main() performs at runtime.
func TestEmbeddedMetaModelSHA256(t *testing.T) {
	sum := sha256.Sum256(metaModelJSON)
	if got := hex.EncodeToString(sum[:]); got != metaModelSHA256 {
		t.Fatalf("metaModel.json sha256 = %s, want %s (pinned in main.go)", got, metaModelSHA256)
	}
}

// TestGenerateDeterministic proves the codegen invariant this migration
// depends on: identical input always produces byte-identical output, so
// `go generate` twice in a row is a clean `git diff`.
func TestGenerateDeterministic(t *testing.T) {
	first, err := Generate(metaModelJSON)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	second, err := Generate(metaModelJSON)
	if err != nil {
		t.Fatalf("Generate (second run): %v", err)
	}
	if !bytes.Equal(first, second) {
		t.Fatalf("Generate is not deterministic: two runs on the same input produced different output")
	}
}

