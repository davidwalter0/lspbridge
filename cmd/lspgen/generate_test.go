// TestResolveTypeRejectsUnsupportedKinds locks in the fail-loud contract: a
// type kind this generator has no rule for (or an unregistered reference)
// must error, never silently fall back to a guess.
func TestResolveTypeRejectsUnsupportedKinds(t *testing.T) {
	noNames := map[string]bool{}
	noExternal := map[string]string{}

	t.Run("unsupported kind", func(t *testing.T) {
		_, _, err := resolveType(anyType{Kind: "or"}, noNames, noNames, noExternal)
		if err == nil {
			t.Fatal("resolveType(or) = nil error, want error")
		}
	})
	t.Run("unresolved reference", func(t *testing.T) {
		_, _, err := resolveType(anyType{Kind: "reference", Name: "SomeUnregisteredType"}, noNames, noNames, noExternal)
		if err == nil {
			t.Fatal("resolveType(reference to unregistered type) = nil error, want error")
		}
	})
	t.Run("unsupported base", func(t *testing.T) {
		_, _, err := resolveType(anyType{Kind: "base", Name: "RegExp"}, noNames, noNames, noExternal)
		if err == nil {
			t.Fatal("resolveType(base RegExp) = nil error, want error")
		}
	})
	t.Run("array missing element", func(t *testing.T) {
		_, _, err := resolveType(anyType{Kind: "array"}, noNames, noNames, noExternal)
		if err == nil {
			t.Fatal("resolveType(array, no element) = nil error, want error")
		}
	})
}

// TestBuildStructOnlyFieldsRejectsUnknownName ensures a typo in a
// structConfig.onlyFields entry fails generation instead of silently
// dropping a field.
func TestBuildStructOnlyFieldsRejectsUnknownName(t *testing.T) {
	var mm metaModel
	if err := json.Unmarshal(metaModelJSON, &mm); err != nil {
		t.Fatalf("unmarshal metaModel.json: %v", err)
	}
	bn := newByName(&mm)

	cfg := structConfig{name: "Position", onlyFields: []string{"line", "notAnActualProperty"}}
	_, _, err := buildStruct(cfg, bn, map[string]bool{}, map[string]bool{}, map[string]string{})
	if err == nil {
		t.Fatal("buildStruct with a bogus onlyFields entry = nil error, want error")
	}
}
